function Btn({ onClick, children, sm }) {
  return (
    <button onClick={onClick} style={{
      background: "transparent",
      border: "1px solid #2a2a2a",
      color: "#555",
      fontFamily: F,
      fontSize: sm ? 11 : 13,
      letterSpacing: sm ? 2 : 3,
      padding: sm ? "9px 14px" : "13px 14px",
      cursor: "pointer",
      transition: "border-color 0.15s, color 0.15s",
    }}>
      {children}
    </button>
  );
}

